"""
FastAPI Backend for Real-Time Sales Ranking Engine.

Serves the current ranking state generated by Stage 8 (Ranking Engine)
and handles demo burst mode triggers.
"""

import json
import logging
from typing import Any, Dict, Optional

from fastapi import FastAPI, HTTPException, status
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

from config.settings import Settings

logger = logging.getLogger("FastAPIBackend")

# Initialize settings
settings = Settings()

app = FastAPI(
    title="Real-Time Top-Selling Product & Intraday Momentum Ranking API",
    description="Serving layer for real-time sales ranking state and burst triggers.",
    version="1.0.0",
)

# Configure CORS
origins = getattr(settings, "CORS_ORIGINS", ["http://localhost:5173", "http://127.0.0.1:5173"])
app.add_middleware(
    CORSMiddleware,
    allow_origins=origins,
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


class BurstRequest(BaseModel):
    product_id: int = Field(..., description="ID of the product to trigger burst for")
    multiplier: Optional[int] = Field(None, description="Burst transaction multiplier")
    duration_seconds: Optional[int] = Field(None, description="Burst duration in seconds")


@app.get("/api/health")
def health_check() -> Dict[str, Any]:
    """
    Health check endpoint returning system health and current state overview.
    """
    ranking_file = settings.RANKING_OUTPUT_FILE
    last_updated = None
    current_window = None

    if ranking_file.exists():
        try:
            with open(ranking_file, "r", encoding="utf-8") as f:
                data = json.load(f)
                if isinstance(data, dict):
                    last_updated = data.get("last_updated")
                    current_window = data.get("window_id")
        except Exception as e:
            logger.warning(f"Health check failed to read ranking output: {e}")

    return {
        "status": "ok",
        "last_updated": last_updated,
        "current_window": current_window,
    }


@app.get("/api/rankings")
def get_rankings() -> Dict[str, Any]:
    """
    Get latest ranking state generated by Stage 8 Ranking Engine.
    FastAPI serves the JSON file directly without performing calculations.
    """
    ranking_file = settings.RANKING_OUTPUT_FILE

    if not ranking_file.exists():
        return {
            "status": "no_data",
            "message": "Ranking output file does not exist yet.",
            "last_updated": None,
            "window_id": None,
            "window_size_seconds": settings.WINDOW_SIZE,
            "total_windows_processed": 0,
            "top_10": [],
            "momentum_movers": [],
        }

    try:
        with open(ranking_file, "r", encoding="utf-8") as f:
            data = json.load(f)
        if not isinstance(data, dict):
            return {
                "status": "invalid_state",
                "message": "Ranking output state is malformed.",
                "last_updated": None,
                "window_id": None,
                "window_size_seconds": settings.WINDOW_SIZE,
                "total_windows_processed": 0,
                "top_10": [],
                "momentum_movers": [],
            }
        return data
    except (json.JSONDecodeError, OSError) as e:
        logger.error(f"Error reading ranking output file: {e}")
        return {
            "status": "error",
            "message": "Failed to read ranking output state.",
            "last_updated": None,
            "window_id": None,
            "window_size_seconds": settings.WINDOW_SIZE,
            "total_windows_processed": 0,
            "top_10": [],
            "momentum_movers": [],
        }


@app.post("/api/burst", status_code=status.HTTP_200_OK)
def trigger_burst(payload: BurstRequest) -> Dict[str, Any]:
    """
    Trigger burst mode for a specific product by writing to state/burst_signal.json.
    Consumed by the Stage 6 Kafka Producer.
    """
    if payload.product_id <= 0:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="product_id must be a positive integer",
        )

    multiplier = (
        payload.multiplier
        if payload.multiplier is not None
        else settings.BURST_MULTIPLIER
    )
    if multiplier <= 0:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="multiplier must be a positive integer",
        )

    duration_seconds = (
        payload.duration_seconds
        if payload.duration_seconds is not None
        else settings.BURST_DURATION
    )
    if duration_seconds <= 0:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="duration_seconds must be a positive integer",
        )

    burst_data = {
        "product_id": payload.product_id,
        "multiplier": multiplier,
        "duration_seconds": duration_seconds,
    }

    try:
        settings.STATE_DIR.mkdir(parents=True, exist_ok=True)
        tmp_file = settings.BURST_SIGNAL_FILE.with_suffix(".tmp")
        with open(tmp_file, "w", encoding="utf-8") as f:
            json.dump(burst_data, f, indent=2)
        tmp_file.replace(settings.BURST_SIGNAL_FILE)
    except Exception as e:
        logger.error(f"Failed to write burst signal file: {e}")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to write burst signal",
        )

    return {
        "status": "burst_started",
        "product_id": payload.product_id,
        "multiplier": multiplier,
        "duration_seconds": duration_seconds,
    }


if __name__ == "__main__":
    import uvicorn

    uvicorn.run("api.main:app", host=settings.API_HOST, port=settings.API_PORT, reload=True)
